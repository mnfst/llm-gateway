import type { ProviderParamSpecService } from '../provider-param-spec.service';

const DATA_FILE_SUFFIX = 'generated/data.js';

const FIXTURE_CATALOG = [
  {
    provider: 'openai',
    authType: 'api_key',
    model: 'gpt-fixture',
    params: [
      {
        path: 'max_tokens',
        label: 'Max tokens',
        description: 'Maximum number of tokens to generate.',
        group: 'generation_length',
        type: 'integer',
        range: { min: 1 },
      },
    ],
  },
];

// The generator serializes the catalog with JSON.stringify(..., 4).
const CATALOG_LITERAL = JSON.stringify(FIXTURE_CATALOG, null, 4);

const LAYOUT_0_0_57 = [
  '// AUTO-GENERATED by packages/modelparams/scripts/codegen.ts. Do not edit by hand.',
  `export const CATALOG = ${CATALOG_LITERAL};`,
  'function authSuffix(authType) {',
  "  return authType === 'api_key' ? '' : `:${authType}`;",
  '}',
  '',
].join('\n');

const LAYOUT_0_0_58_AND_LATER = [
  '// AUTO-GENERATED by packages/modelparams/scripts/codegen.ts. Do not edit by hand.',
  `const GENERATED_CATALOG = ${CATALOG_LITERAL};`,
  'export const CATALOG = GENERATED_CATALOG;',
  'function authSuffix(authType) {',
  "  return authType === 'api_key' ? '' : `:${authType}`;",
  '}',
  '',
].join('\n');

/**
 * Builds the service with the modelparams data file replaced by `dataFile`.
 * Every other read is delegated to the real fs so module loading is unaffected.
 */
function createServiceWithDataFile(dataFile: string): ProviderParamSpecService {
  let service!: ProviderParamSpecService;
  jest.isolateModules(() => {
    jest.doMock('node:fs', () => {
      const actual = jest.requireActual<typeof import('node:fs')>('node:fs');
      return {
        ...actual,
        readFileSync: jest.fn(
          (path: Parameters<typeof actual.readFileSync>[0], ...rest: unknown[]) =>
            typeof path === 'string' && path.endsWith(DATA_FILE_SUFFIX)
              ? dataFile
              : (actual.readFileSync as (...args: unknown[]) => unknown)(path, ...rest),
        ),
      };
    });
    const mod =
      // eslint-disable-next-line @typescript-eslint/no-require-imports
      require('../provider-param-spec.service') as typeof import('../provider-param-spec.service');
    service = new mod.ProviderParamSpecService();
  });
  return service;
}

describe('ProviderParamSpecService modelparams catalog loader', () => {
  const originalApiDisabled = process.env.MODELPARAMS_API_DISABLED;

  beforeEach(() => {
    process.env.MODELPARAMS_API_DISABLED = 'true';
  });

  afterEach(() => {
    jest.dontMock('node:fs');
    jest.resetModules();
    if (originalApiDisabled === undefined) delete process.env.MODELPARAMS_API_DISABLED;
    else process.env.MODELPARAMS_API_DISABLED = originalApiDisabled;
  });

  it('parses the export const CATALOG layout used up to modelparams 0.0.57', async () => {
    const service = createServiceWithDataFile(LAYOUT_0_0_57);

    const specs = await service.getSpecs('openai', 'api_key', 'gpt-fixture');

    expect(specs.map((spec) => spec.path)).toEqual(['max_tokens']);
  });

  it('parses the GENERATED_CATALOG layout used from modelparams 0.0.58', async () => {
    const service = createServiceWithDataFile(LAYOUT_0_0_58_AND_LATER);

    const specs = await service.getSpecs('openai', 'api_key', 'gpt-fixture');

    expect(specs.map((spec) => spec.path)).toEqual(['max_tokens']);
  });

  it('throws when the catalog file has an unknown shape', () => {
    expect(() => createServiceWithDataFile('export const OTHER = 1;\n')).toThrow(
      'modelparams package catalog file has an unknown shape',
    );
  });
});
